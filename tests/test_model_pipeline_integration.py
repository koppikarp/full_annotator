"""Integration test verifying OpsPipeline with trained blob and base models."""

import os
import tempfile
import numpy as np
import pandas as pd
import pytest

from popcrop.config import PipelineConfig
from popcrop.pipeline import OpsPipeline
from popcrop.io.codebook import Codebook
from popcrop.models.trainer import BlobModelTrainer, BaseModelTrainer
from tests.test_model_training import synthetic_blob_ground_truth, synthetic_base_ground_truth


def test_pipeline_with_trained_models(synthetic_blob_ground_truth, synthetic_base_ground_truth):
    """Verifies that OpsPipeline uses trained models to score blobs and call bases with distribution features."""
    with tempfile.TemporaryDirectory() as tmpdir:
        # 1. Train models
        blob_trainer = BlobModelTrainer(test_size=0.20, random_state=42)
        blob_trainer.train(synthetic_blob_ground_truth, output_dir=tmpdir, model_name="trained_blob")
        blob_model_path = os.path.join(tmpdir, "trained_blob.joblib")

        base_trainer = BaseModelTrainer(test_size=0.20, random_state=42)
        base_trainer.train(synthetic_base_ground_truth, output_dir=tmpdir, model_name="trained_base")
        base_model_path = os.path.join(tmpdir, "trained_base.joblib")

        # 2. Setup synthetic image stack (T=2 cycles, C=2 channels, H=60, W=60)
        T, C, H, W = 2, 2, 60, 60
        sbs_stack = np.ones((T, C, H, W), dtype=np.float32) * 100.0
        # Cycle 0: Base A (Green dominant) at center (cy=30, cx=30)
        sbs_stack[0, 1, 25:35, 25:35] = 5000.0  # Green
        sbs_stack[0, 0, 25:35, 25:35] = 150.0   # Red
        # Cycle 1: Base T (Red dominant)
        sbs_stack[1, 0, 25:35, 25:35] = 4500.0  # Red
        sbs_stack[1, 1, 25:35, 25:35] = 120.0   # Green

        dapi = np.zeros((H, W), dtype=np.float32)
        nuclear_mask = np.zeros((H, W), dtype=np.int32)
        nuclear_mask[20:40, 20:40] = 1

        # Codebook with expected barcode "AT"
        codebook_df = pd.DataFrame({
            "barcode": ["AT", "CG", "TA"],
            "gene": ["GeneA", "GeneB", "GeneC"]
        })
        cb = Codebook(df_codebook=codebook_df)

        # 3. Configure Pipeline with trained models
        config = PipelineConfig(analysis_mode="legacy")
        config.blob_classifier.model_path = blob_model_path
        config.color_calling.calibrated_color_model_path = base_model_path

        pipeline = OpsPipeline(config=config)
        assert pipeline.classifier.pipeline is not None
        assert pipeline.color_caller.model_caller is not None
        assert pipeline.color_caller.model_caller.pipeline is not None

        # 4. Run pipeline
        df_nuclei, df_comp, _ = pipeline.run_on_arrays(
            sbs_stack=sbs_stack,
            dapi_image=dapi,
            nuclear_mask=nuclear_mask,
            codebook=cb
        )

        assert not df_comp.empty
        rec = df_comp.iloc[0]

        # Verify blob score from trained model
        assert rec["p_real_blob"] > 0.70

        # Verify cycle probabilities generated by trained base caller model
        cycle_probs = rec["cycle_probabilities"]
        assert len(cycle_probs) == 2
        # Cycle 0: Base A -> green dominant
        assert cycle_probs[0]["green"] > cycle_probs[0]["red"]
        # Cycle 1: Base T -> red dominant
        assert cycle_probs[1]["red"] > cycle_probs[1]["green"]

        # Verify decoded sequence matches "AT"
        assert rec["called_sequence"] == "AT"
        assert rec["best_gene"] == "GeneA"

        # Verify cycle distribution features matching annotator are present
        assert "cycle_distribution_features" in rec
        dist_feats = rec["cycle_distribution_features"]
        assert len(dist_feats) == 2
        for cf in dist_feats:
            assert "green_median" in cf
            assert "red_median" in cf
            assert "rg_ratio_median" in cf
            assert "green_trimmed_mean" in cf
            assert "red_trimmed_mean" in cf
            assert cf["blob_area"] > 0
